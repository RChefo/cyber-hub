import { describe, expect, it } from "vitest";
import type { Finding, Project } from "@/lib/types";
import { buildMarkdownReport, countBySeverity, sortFindings } from "./report";

const project: Project = {
  id: 1,
  name: "Acme external assessment",
  description: "Quarterly external test.",
  status: "active",
  scopeNotes: "Testing window 09:00-17:00 UTC.",
  notes: "",
  startDate: "2026-11-01",
  endDate: "2026-11-15",
  createdAt: "2026-11-01T00:00:00Z",
  updatedAt: "2026-11-02T00:00:00Z",
  targets: [
    { id: 1, value: "*.acme.test", kind: "wildcard", inScope: true, note: "" },
    { id: 2, value: "vpn.acme.test", kind: "domain", inScope: false, note: "Production VPN | do not touch" },
  ],
};

const f = (id: number, severity: Finding["severity"], status: Finding["status"], updatedAt = "2026-11-02T00:00:00Z"): Finding => ({
  id,
  projectId: 1,
  title: `Finding ${id}`,
  severity,
  status,
  description: id === 2 ? "Line one\nLine two" : "",
  affectedTarget: "app.acme.test",
  cve: id === 2 ? "CVE-2021-44228" : "",
  evidence: id === 2 ? [{ label: "Request", reference: "evidence/req-2.txt" }] : [],
  createdAt: updatedAt,
  updatedAt,
});

describe("findings helpers", () => {
  it("sorts by severity then most recent", () => {
    const sorted = sortFindings([f(1, "low", "open"), f(2, "critical", "open"), f(3, "low", "open", "2026-11-03T00:00:00Z")]);
    expect(sorted.map((x) => x.id)).toEqual([2, 3, 1]);
  });
  it("counts severities, optionally excluding closed findings", () => {
    const list = [f(1, "high", "open"), f(2, "high", "resolved"), f(3, "info", "false_positive")];
    expect(countBySeverity(list).high).toBe(2);
    expect(countBySeverity(list, true)).toEqual({ critical: 0, high: 1, medium: 0, low: 0, info: 0 });
  });
});

describe("buildMarkdownReport", () => {
  const md = buildMarkdownReport(project, [f(1, "low", "open"), f(2, "critical", "confirmed")], new Date("2026-11-03T12:00:00Z"));

  it("includes summary, scope and findings in severity order", () => {
    expect(md).toContain("# Acme external assessment");
    expect(md).toContain("generated by Cyber Hub on 2026-11-03");
    expect(md).toContain("Critical 1");
    expect(md.indexOf("### 1. Finding 2")).toBeLessThan(md.indexOf("### 2. Finding 1"));
    expect(md).toContain("- **CVE:** CVE-2021-44228");
    expect(md).toContain("- Request: `evidence/req-2.txt`");
    expect(md).toContain("### Rules of engagement");
  });

  it("escapes table cells", () => {
    expect(md).toContain("Production VPN \\| do not touch");
    expect(md).toContain("| `vpn.acme.test` | domain | Out of scope |");
  });

  it("handles empty projects without fabricating content", () => {
    const empty = buildMarkdownReport({ ...project, targets: [], scopeNotes: "", description: "" }, []);
    expect(empty).toContain("No scope entries recorded.");
    expect(empty).toContain("No findings recorded.");
  });
});
