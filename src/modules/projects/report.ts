import type { Finding, Project, Severity } from "@/lib/types";

const SEVERITY_ORDER: Severity[] = ["critical", "high", "medium", "low", "info"];
const SEVERITY_LABEL: Record<Severity, string> = { critical: "Critical", high: "High", medium: "Medium", low: "Low", info: "Info" };
const STATUS_LABEL: Record<Finding["status"], string> = {
  open: "Open",
  confirmed: "Confirmed",
  reported: "Reported",
  resolved: "Resolved",
  false_positive: "False positive",
};

export function sortFindings(findings: Finding[]): Finding[] {
  return [...findings].sort(
    (a, b) => SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity) || b.updatedAt.localeCompare(a.updatedAt),
  );
}

export function countBySeverity(findings: Finding[], onlyActive = false): Record<Severity, number> {
  const out: Record<Severity, number> = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  for (const f of findings) {
    if (onlyActive && (f.status === "resolved" || f.status === "false_positive")) continue;
    out[f.severity]++;
  }
  return out;
}

/** Escape characters that would break Markdown table cells. */
function cell(v: string): string {
  return v.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim() || "—";
}

/** Builds a self-contained Markdown assessment report from local project data. */
export function buildMarkdownReport(project: Project, findings: Finding[], generatedAt: Date = new Date()): string {
  const lines: string[] = [];
  lines.push(`# ${project.name}`);
  lines.push("");
  lines.push(`_Assessment report generated by Cyber Hub on ${generatedAt.toISOString().slice(0, 10)}._`);
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push(`- **Status:** ${project.status.charAt(0).toUpperCase()}${project.status.slice(1)}`);
  lines.push(`- **Period:** ${project.startDate ?? "not set"} → ${project.endDate ?? "not set"}`);
  const counts = countBySeverity(findings);
  lines.push(
    `- **Findings:** ${findings.length} (${SEVERITY_ORDER.map((s) => `${SEVERITY_LABEL[s]} ${counts[s]}`).join(", ")})`,
  );
  if (project.description.trim()) {
    lines.push("");
    lines.push(project.description.trim());
  }

  lines.push("");
  lines.push("## Authorized scope");
  lines.push("");
  const inScope = project.targets.filter((t) => t.inScope);
  const outScope = project.targets.filter((t) => !t.inScope);
  if (!project.targets.length) {
    lines.push("No scope entries recorded.");
  } else {
    lines.push("| Target | Type | Scope | Note |");
    lines.push("| --- | --- | --- | --- |");
    for (const t of [...inScope, ...outScope]) {
      lines.push(`| \`${cell(t.value)}\` | ${t.kind} | ${t.inScope ? "In scope" : "Out of scope"} | ${cell(t.note)} |`);
    }
  }
  if (project.scopeNotes.trim()) {
    lines.push("");
    lines.push("### Rules of engagement");
    lines.push("");
    lines.push(project.scopeNotes.trim());
  }

  lines.push("");
  lines.push("## Findings");
  lines.push("");
  const sorted = sortFindings(findings);
  if (!sorted.length) {
    lines.push("No findings recorded.");
  } else {
    lines.push("| # | Title | Severity | Status | Affected |");
    lines.push("| --- | --- | --- | --- | --- |");
    sorted.forEach((f, i) => {
      lines.push(`| ${i + 1} | ${cell(f.title)} | ${SEVERITY_LABEL[f.severity]} | ${STATUS_LABEL[f.status]} | ${cell(f.affectedTarget)} |`);
    });
    sorted.forEach((f, i) => {
      lines.push("");
      lines.push(`### ${i + 1}. ${f.title}`);
      lines.push("");
      lines.push(`- **Severity:** ${SEVERITY_LABEL[f.severity]}`);
      lines.push(`- **Status:** ${STATUS_LABEL[f.status]}`);
      if (f.affectedTarget) lines.push(`- **Affected target:** \`${f.affectedTarget}\``);
      if (f.cve) lines.push(`- **CVE:** ${f.cve}`);
      if (f.description.trim()) {
        lines.push("");
        lines.push(f.description.trim());
      }
      if (f.evidence.length) {
        lines.push("");
        lines.push("**Evidence**");
        lines.push("");
        for (const e of f.evidence) lines.push(`- ${e.label}: \`${e.reference}\``);
      }
    });
  }

  if (project.notes.trim()) {
    lines.push("");
    lines.push("## Notes");
    lines.push("");
    lines.push(project.notes.trim());
  }
  lines.push("");
  return lines.join("\n");
}
