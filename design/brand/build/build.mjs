// Writes every vector asset of the ExploitX identity, and the design tokens.
// usage: node design/brand/build/build.mjs   (then export.mjs for PNG, ICO and social images)
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import * as B from "./brand.mjs";
import { tokens, tokensCss } from "./tokens.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = (rel, text) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
  return rel;
};
const { C } = B;
const UV = tokens.brand.ultraviolet;
const onDark = { uv: UV[500], target: C.bone, text: C.bone };
const onLight = { uv: UV[700], target: C.ink, text: C.ink };
const mono = { uv: "currentColor", target: "currentColor", text: "currentColor" };

const written = [
  out("logo-primary.svg", B.svg(B.stacked(onDark), "ExploitX")),
  out("logo-horizontal.svg", B.svg(B.horizontal(onDark), "ExploitX")),
  out("logo-compact.svg", B.svg(B.horizontal({ ...onDark, compact: true }), "ExploitX")),
  out("logo-dark.svg", B.svg(B.horizontal(onDark), "ExploitX")),
  out("logo-light.svg", B.svg(B.horizontal(onLight), "ExploitX")),
  out("logo-primary-light.svg", B.svg(B.stacked(onLight), "ExploitX")),
  out("logo-compact-light.svg", B.svg(B.horizontal({ ...onLight, compact: true }), "ExploitX")),
  out("logo-monochrome.svg", B.svg(B.horizontal(mono), "ExploitX")),
  out("logo-monochrome-stacked.svg", B.svg(B.stacked(mono), "ExploitX")),
  out("logo-symbol.svg", B.symbolSvg({ uv: UV[500], target: C.bone })),
  out("logo-symbol-light.svg", B.symbolSvg({ uv: UV[700], target: C.ink })),
  out("logo-symbol-monochrome.svg", B.symbolSvg({ uv: "currentColor", target: "currentColor" })),
  out("logo-symbol-small.svg", B.symbolSvg({ uv: UV[500], target: C.bone, gap: 0, title: "ExploitX symbol (small sizes)" })),
  out("logo-wordmark.svg", wordmarkSvg(C.bone)),
  out("logo-wordmark-light.svg", wordmarkSvg(C.ink)),
  out("app-icon.svg", B.appIcon()),
  out("app-icon-small.svg", B.appIcon({ small: true })),
  out("favicon.svg", B.appIcon({ small: true })),
  out("tokens.json", JSON.stringify(tokens, null, 2) + "\n"),
  out("tokens.css", tokensCss()),
];

// The same geometry for inline use in the app (and, as a copy, in the website repository RChefo/ExploitX-Web;
// its docs/BRAND.md says how to sync). React components draw it with
// CSS colours, so one source serves dark, light and monochrome).
const logoData = (() => {
  const sym = B.symbolPolygons();
  const symSmall = B.symbolPolygons({ gap: 0 });
  const wm = B.wordmarkPaths();
  const wmc = B.wordmarkPaths({ compact: true });
  const r = (n) => Math.round(n * 10) / 10;
  return `// Generated by design/brand/build/build.mjs from the ExploitX brand geometry: do not edit by hand.
/** The symbol on its 64-unit grid; the mark itself spans the viewBox "6 8 52 48". */
export const SYMBOL = {
  viewBox: "6 8 52 48",
  left: "${B.poly(sym.left)}",
  right: "${B.poly(sym.right)}",
  /** no hairline gap: for 24 px and smaller */
  leftSmall: "${B.poly(symSmall.left)}",
  rightSmall: "${B.poly(symSmall.right)}",
} as const;

/** "ExploitX" outlines, cap height ${wm.capHeight} units, baseline at y = ${wm.capHeight}; translate by \`shift\` first. */
export const WORDMARK = {
  capHeight: ${wm.capHeight},
  descender: ${wm.descender},
  shift: ${r(wm.shift)},
  width: ${r(wm.width)},
  d: "${wm.d}",
  /** small-size version: the X's tips touch */
  dCompact: "${wmc.d}",
  widthCompact: ${r(wmc.width)},
} as const;
`;
})();
// brand-preview.svg: one board with the whole identity (text uses the brand fonts when installed)
written.push(out("brand-preview.svg", brandPreview()));
function brandPreview() {
  const W = 1600, Hh = 1180;
  const night = tokens.neutral.background;
  const nest = (svgText, x, y, w, h) => svgText.replace(/^<svg /, `<svg x="${x}" y="${y}" width="${w}" height="${h}" `).replace(/ width="[\d.]+" height="[\d.]+" role/, " role");
  const hz = B.horizontal(onDark), hzl = B.horizontal(onLight), st = B.stacked(onDark), mo = B.horizontal({ uv: C.ink, target: C.ink, text: C.ink });
  const lock = (L, x, y, w) => `<svg x="${x}" y="${y}" width="${w}" height="${(w * L.height) / L.width}" viewBox="0 0 ${L.width} ${L.height}">${L.body}</svg>`;
  const label = (x, y, t, size = 15, fill = tokens.neutral.textMuted, family = "IBM Plex Sans, Segoe UI, sans-serif", weight = 400) =>
    `<text x="${x}" y="${y}" font-family="${family}" font-size="${size}" font-weight="${weight}" fill="${fill}">${t}</text>`;
  const swatches = [
    ["Ultraviolet 500", UV[500], "#FFFFFF"], ["Ultraviolet 600", UV[600], "#FFFFFF"], ["Ultraviolet 300", UV[300], C.ink], ["Bone", C.bone, C.ink],
    ["Ink", C.ink, C.bone], ["Night", night, C.bone], ["Surface", tokens.neutral.surface, C.bone], ["Signal", tokens.brand.signal, C.ink],
  ];
  const sev = Object.entries(tokens.severity);
  let s = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${Hh}" width="${W}" height="${Hh}" role="img" aria-label="ExploitX brand overview"><title>ExploitX brand overview</title>`;
  s += `<rect width="${W}" height="${Hh}" fill="${night}"/>`;
  // header
  s += lock(hz, 64, 56, 420) + label(64, 196, "Cybersecurity intelligence &amp; security research platform", 22, tokens.neutral.textSecondary);
  s += label(1536, 92, "Brand overview · design/brand", 15, tokens.neutral.textMuted).replace("<text ", '<text text-anchor="end" ');
  // symbol + stacked
  s += `<rect x="64" y="236" width="440" height="440" rx="28" fill="${tokens.neutral.surface}"/>` + nest(B.symbolSvg({ uv: UV[500], target: C.bone }), 124, 296, 320, 320);
  s += label(64, 706, "Symbol: Convergence", 16, C.bone, undefined, 500) + label(64, 730, "Two chevrons meet at one point: the operator’s input and its target.");
  s += `<rect x="536" y="236" width="440" height="440" rx="28" fill="${tokens.neutral.surface}"/>` + lock(st, 576, 296, 360);
  s += label(536, 706, "Primary (stacked) lockup", 16, C.bone, undefined, 500) + label(536, 730, "Hero, splash, About. Horizontal lockup everywhere else.");
  // light + mono + icons
  s += `<rect x="1008" y="236" width="528" height="210" rx="28" fill="${tokens.neutral.light.background}"/>` + lock(hzl, 1056, 300, 432);
  s += `<rect x="1008" y="466" width="528" height="210" rx="28" fill="#FFFFFF"/>` + lock(mo, 1056, 530, 432);
  s += label(1008, 706, "On light, and monochrome", 16, C.bone, undefined, 500) + label(1008, 730, "Ultraviolet 700 and Ink on light; one colour when colour is not possible.");
  // palette
  s += label(64, 800, "Colour", 16, C.bone, undefined, 500);
  swatches.forEach(([n, c, fg], i) => {
    const x = 64 + i * 184;
    s += `<rect x="${x}" y="818" width="168" height="112" rx="16" fill="${c}"${c === night ? ` stroke="#FFFFFF" stroke-opacity="0.1"` : ""}/>`;
    s += label(x + 16, 892, n, 14, fg, undefined, 500) + label(x + 16, 914, c.toUpperCase(), 13, fg, "JetBrains Mono, Consolas, monospace");
  });
  s += label(64, 966, "Severity (always with its name)", 14, tokens.neutral.textMuted);
  sev.forEach(([n, c], i) => {
    const x = 64 + i * 150;
    s += `<rect x="${x}" y="982" width="136" height="34" rx="9" fill="${c}" fill-opacity="0.16"/>` + label(x + 14, 1004, n[0].toUpperCase() + n.slice(1), 14, c, undefined, 500);
  });
  s += label(840, 966, "Data visualisation, categorical", 14, tokens.neutral.textMuted);
  tokens.dataviz.categorical.forEach((c, i) => (s += `<rect x="${840 + i * 87}" y="982" width="75" height="34" rx="9" fill="${c}"/>`));
  // type
  s += label(64, 1080, "Archivo", 34, C.bone, "Archivo, IBM Plex Sans, sans-serif", 600) + label(250, 1080, "display and headings", 15);
  s += label(560, 1080, "IBM Plex Sans", 30, C.bone, "IBM Plex Sans, sans-serif", 500) + label(780, 1080, "interface and text", 15);
  s += label(1060, 1080, "JetBrains Mono", 26, UV[300], "JetBrains Mono, Consolas, monospace", 500) + label(1310, 1080, "commands, data", 15);
  s += label(64, 1132, "ExploitX · exploitx.net · editable sources: design/brand/build", 13, tokens.neutral.textFaint);
  return s + "</svg>\n";
}

const repo = join(root, "..", "..");
for (const rel of ["src/components/brand/logoData.ts"]) {
  mkdirSync(dirname(join(repo, rel)), { recursive: true });
  writeFileSync(join(repo, rel), logoData);
  written.push(rel);
}

function wordmarkSvg(fill) {
  const wm = B.wordmarkPaths();
  const pad = wm.capHeight * 0.5;
  const w = wm.width + pad * 2;
  const h = wm.capHeight + wm.descender + pad * 2;
  return B.svg({ body: `<path fill="${fill}" transform="translate(${pad + wm.shift} ${pad})" d="${wm.d}"/>`, width: w, height: h }, "ExploitX");
}

