#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SystemInfo {
    pub os: String,
    pub os_name: String,
    pub os_version: String,
    pub kernel_version: String,
    pub hostname: String,
    pub arch: String,
    pub cpu_brand: String,
    pub cpu_cores: usize,
    pub total_memory: u64,
    pub used_memory: u64,
    pub uptime_secs: u64,
    pub app_version: String,
    pub data_dir: String,
    pub db_schema_version: i64,
    pub running_processes: usize,
}

/// The third-party licenses file bundled with ExploitX (Mission 14, generated by
/// `scripts/licenses.mjs notices`): its path, or None when this build has no bundled resources.
/// Read-only: the page shows the path and links to the online notices; nothing is opened here.
#[tauri::command]
pub fn third_party_notices_path(app: AppHandle) -> Option<String> {
    app.path()
        .resolve("THIRD_PARTY_LICENSES.txt", tauri::path::BaseDirectory::Resource)
        .ok()
        .filter(|p| p.is_file())
        .map(|p| display_path(&p.display().to_string()))
}

/// A path as people type it: Windows' extended-length prefix (`\\?\C:\…`, from resolving the
/// resource folder) is dropped before a drive letter; UNC and other paths are kept as they are.
fn display_path(path: &str) -> String {
    match path.strip_prefix(r"\\?\") {
        Some(rest) if rest.as_bytes().get(1) == Some(&b':') => rest.to_string(),
        _ => path.to_string(),
    }
}

#[tauri::command]
pub async fn system_info(app: AppHandle, db: State<'_, Db>, pm: State<'_, ProcessManager>) -> AppResult<SystemInfo> {
    let (cpu_brand, cpu_cores, total, used) = tauri::async_runtime::spawn_blocking(|| {
        let mut sys = sysinfo::System::new();
        sys.refresh_memory();
        sys.refresh_cpu_all();
        let brand = sys.cpus().first().map(|c| c.brand().trim().to_string()).unwrap_or_default();
        (brand, sys.cpus().len(), sys.total_memory(), sys.used_memory())
    })
    .await
    .map_err(|e| AppError::Internal(e.to_string()))?;
    let data_dir = crate::util::data_dir(&app)?.to_string_lossy().to_string();
    Ok(SystemInfo {
        os: current_os().into(),
        os_name: sysinfo::System::name().unwrap_or_default(),
        os_version: sysinfo::System::os_version().unwrap_or_default(),
        kernel_version: sysinfo::System::kernel_version().unwrap_or_default(),
        hostname: sysinfo::System::host_name().unwrap_or_default(),
        arch: std::env::consts::ARCH.into(),
        cpu_brand,
        cpu_cores,
        total_memory: total,
        used_memory: used,
        uptime_secs: sysinfo::System::uptime(),
        app_version: app.package_info().version.to_string(),
        data_dir,
        db_schema_version: db.schema_version()?,
        running_processes: pm.running_ids().len(),
    })
}

/// Opens a new system terminal window in the home folder. No command is passed to the terminal:
/// the UI copies commands to the clipboard instead, so nothing runs without the user pressing
/// Enter. It takes no directory from the page (Mission 7): a network path there would make
/// Windows connect to that host with the user's credentials. It starts a program, so it asks in a
/// native dialog first (Mission 8): a page cannot open terminals by itself.
#[tauri::command]
pub async fn open_terminal(app: AppHandle) -> AppResult<String> {
    if !crate::confirm::native(&app, "Open a terminal", "Open a terminal window in your home folder?\n\nExploitX types nothing into it: a command you copied runs only if you paste it there and press Enter.".to_string(), "Open terminal").await {
        return Err(AppError::Cancelled("No terminal was opened".into()));
    }
    let dir = dirs_home().filter(|d| !crate::util::is_network_or_device_path(&d.to_string_lossy())).unwrap_or_else(|| PathBuf::from("."));

    let spawn = |mut cmd: Command| -> std::io::Result<()> {
        cmd.current_dir(&dir).stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null());
        cmd.spawn().map(|_| ())
    };

    match current_os() {
        "windows" => {
            if let Some(wt) = find_binary("wt") {
                let mut c = Command::new(wt);
                c.arg("-d").arg(&dir);
                if spawn(c).is_ok() {
                    return Ok("Windows Terminal".into());
                }
            }
            #[cfg(windows)]
            {
                use std::os::windows::process::CommandExt;
                let mut c = Command::new(crate::util::system_powershell());
                c.arg("-NoLogo").creation_flags(0x0000_0010); // CREATE_NEW_CONSOLE
                c.current_dir(&dir);
                c.spawn().map_err(|e| AppError::Internal(format!("Could not open a terminal: {e}")))?;
                return Ok("PowerShell".into());
            }
            #[allow(unreachable_code)]
            Err(AppError::Internal("Could not open a terminal".into()))
        }
        "macos" => {
            let mut c = Command::new(crate::util::MACOS_OPEN);
            c.arg("-a").arg("Terminal").arg(&dir);
            spawn(c).map_err(|e| AppError::Internal(format!("Could not open Terminal.app: {e}")))?;
            Ok("Terminal".into())
        }
        _ => {
            for term in ["x-terminal-emulator", "gnome-terminal", "konsole", "xfce4-terminal", "kitty", "alacritty", "xterm"] {
                if let Some(p) = find_binary(term) {
                    if spawn(Command::new(p)).is_ok() {
                        return Ok(term.into());
                    }
                }
            }
            Err(AppError::Internal("No supported terminal emulator found".into()))
        }
    }
}

fn dirs_home() -> Option<PathBuf> {
    std::env::var_os("HOME").or_else(|| std::env::var_os("USERPROFILE")).map(PathBuf::from)
}

/* ─────────────── secrets (OS keychain) ─────────────── */
//
// Provider credentials are provisioned by the application owner with the developer-only
// `cyberhub-keys` tool (see docs/PROVISIONING.md). The app itself only reads them, inside
// the Rust functions that call a provider. No IPC command can read or list a credential, or
// pass one in; the web view only learns whether a service is configured.
//
// TAXII servers (Mission 6) are the analyst's own, so the app can also store their credential:
// the analyst types it into a native OS dialog (`native_prompt`), never into the web view, and
// `store_taxii_secret` writes it to the credential store. Provider keys stay provisioning-only.

pub const SERVICE: &str = "dev.cyberhub.workstation";
pub const NVD_KEY: &str = "nvd_api_key";
/// Every credential ExploitX may use.
pub const KNOWN_SECRETS: &[&str] = &[NVD_KEY, "virustotal_api_key", "abuseipdb_api_key", "otx_api_key", "abusech_auth_key", "shodan_api_key", crate::commands::assistant::ANTHROPIC_KEY];

/// A TAXII server's credential: `taxii_<server number>_<16 hex digits>`, bound to the server's
/// origin, kind of authentication and header (`ti::taxii::secret_name`, Mission 7).
pub fn is_taxii_secret(name: &str) -> bool {
    let Some((id, fingerprint)) = name.strip_prefix("taxii_").and_then(|rest| rest.split_once('_')) else {
        return false;
    };
    !id.is_empty() && id.len() <= 18 && id.bytes().all(|b| b.is_ascii_digit()) && fingerprint.len() == 16 && fingerprint.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

fn entry(name: &str) -> AppResult<keyring::Entry> {
    if !KNOWN_SECRETS.contains(&name) && !is_taxii_secret(name) {
        return Err(validation("Unknown secret name"));
    }
    keyring::Entry::new(SERVICE, name).map_err(|e| AppError::Secret(e.to_string()))
}

/// Backend-only read. Secret values are never returned to the web view.
pub fn read_secret(name: &str) -> Option<String> {
    entry(name).ok()?.get_password().ok().filter(|v| !v.is_empty())
}

/// Whether a credential is present (never its value).
///
/// On Linux the Secret Service is searched without unlocking anything, and an item in a locked
/// keyring counts as present. Reading the value of a locked item makes the desktop ask to unlock
/// the keyring, so pages that only show whether a credential exists opened an unlock prompt, and
/// the TAXII list held the database until it was answered (Mission 9, GNOME). Windows' Credential
/// Manager has nothing to unlock.
pub fn secret_configured(name: &str) -> bool {
    if !KNOWN_SECRETS.contains(&name) && !is_taxii_secret(name) {
        return false;
    }
    #[cfg(target_os = "linux")]
    {
        secret_service_has(name)
    }
    #[cfg(not(target_os = "linux"))]
    {
        read_secret(name).is_some()
    }
}

/// A Secret Service search for the entry keyring writes (service and user name; the target is
/// left out, so entries written by older keyring versions count too). No secret is transferred,
/// so the session needs no encryption. False without a Secret Service.
#[cfg(target_os = "linux")]
fn secret_service_has(name: &str) -> bool {
    use dbus_secret_service::{EncryptionType, SecretService};
    let Ok(ss) = SecretService::connect(EncryptionType::Plain) else { return false };
    let attributes = std::collections::HashMap::from([("service", SERVICE), ("username", name)]);
    ss.search_items(attributes).is_ok_and(|found| !found.unlocked.is_empty() || !found.locked.is_empty())
}

/// Stores a TAXII server's credential (typed into a native dialog) under the entry bound to the
/// server as it is now (`ti::taxii::secret_name`).
pub fn store_taxii_secret(server: &crate::ti::taxii::Server, value: &str) -> AppResult<()> {
    let name = crate::ti::taxii::server_secret_name(server).ok_or_else(|| validation("This server uses no authentication"))?;
    if !is_taxii_secret(&name) {
        return Err(validation("Unknown secret name"));
    }
    entry(&name)?.set_password(value).map_err(|e| AppError::Secret(e.to_string()))
}

/// Deletes a TAXII server's credential, and one stored under the server's number alone (before
/// Mission 7). Only what is stored is deleted, so nothing stored is not an error, also on a
/// computer without a credential store.
pub fn delete_taxii_secret(server: &crate::ti::taxii::Server) -> AppResult<()> {
    let mut names = vec![format!("taxii_{}", server.id)];
    names.extend(crate::ti::taxii::server_secret_name(server));
    for name in names {
        let Ok(e) = keyring::Entry::new(SERVICE, &name) else { continue };
        if e.get_password().is_err() {
            continue;
        }
        match e.delete_credential() {
            Ok(()) | Err(keyring::Error::NoEntry) => {}
            Err(err) => return Err(AppError::Secret(err.to_string())),
        }
    }
    Ok(())
}

/// Write a credential. Only compiled into the developer provisioning tool.
#[cfg(feature = "provisioning")]
pub fn store_secret(name: &str, value: &str) -> AppResult<()> {
    entry(name)?.set_password(value).map_err(|e| AppError::Secret(e.to_string()))
}

/// Delete a credential. Only compiled into the developer provisioning tool.
#[cfg(feature = "provisioning")]
pub fn delete_secret(name: &str) -> AppResult<()> {
    match entry(name)?.delete_credential() {
        Ok(()) | Err(keyring::Error::NoEntry) => Ok(()),
        Err(e) => Err(AppError::Secret(e.to_string())),
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn notices_paths_drop_only_the_extended_length_prefix_before_a_drive() {
        assert_eq!(super::display_path(r"\\?\E:\Cyber Hub\THIRD_PARTY_LICENSES.txt"), r"E:\Cyber Hub\THIRD_PARTY_LICENSES.txt");
        assert_eq!(super::display_path(r"\\?\UNC\server\share\x.txt"), r"\\?\UNC\server\share\x.txt");
        assert_eq!(super::display_path("/usr/lib/Cyber Hub/THIRD_PARTY_LICENSES.txt"), "/usr/lib/Cyber Hub/THIRD_PARTY_LICENSES.txt");
    }

    /// Mission 9 (GNOME): checking whether a credential exists read its value, and with the keyring
    /// locked that made the desktop ask to unlock it. On Linux the check is a search that neither
    /// unlocks nor reads, and it answers for known credential names only.
    #[test]
    fn presence_checks_never_unlock_or_read_a_value() {
        let src = include_str!("system.rs");
        let f = &src[src.find("fn secret_service_has(").unwrap()..];
        let f = &f[..f.find("\n}\n").unwrap()];
        assert!(f.contains("search_items(") && f.contains("found.locked"), "{f}");
        for forbidden in ["get_password", "get_secret", ".unlock(", "read_secret", "EncryptionType::Dh"] {
            assert!(!f.contains(forbidden), "{forbidden} in {f}");
        }
        let p = &src[src.find("pub fn secret_configured(").unwrap()..];
        let p = &p[..p.find("\n}\n").unwrap()];
        assert!(p.contains("secret_service_has(name)"), "{p}");
        assert!(!super::secret_configured("not_a_known_secret"));
    }

    /// Guard: the web view must not be able to read, list, set, test or delete credentials.
    /// Fails if such a command is ever registered in the IPC handler list again.
    #[test]
    fn no_credential_commands_are_exposed_over_ipc() {
        let lib = include_str!("../lib.rs");
        let start = lib.find("generate_handler![").expect("handler list");
        let handlers = &lib[start..start + lib[start..].find("])").expect("end of handler list")];
        let names: Vec<&str> = handlers.lines().map(str::trim).filter(|l| l.contains("::")).collect();
        assert!(names.len() > 50, "handler list parsed");
        for name in names {
            let n = name.to_ascii_lowercase();
            for banned in ["secret", "_key_set", "_key_test", "_key_delete", "credential", "provision", "keychain"] {
                assert!(!n.contains(banned), "credential command exposed over IPC: {name}");
            }
        }
        // the only credential-related information the UI gets is "configured or not"
        assert!(handlers.contains("vt_key_status") && handlers.contains("ti_providers"));
    }

    /// Mission 6: the only commands that store or delete a credential are the TAXII ones, and they
    /// take no credential: the value is typed into a native dialog and never crosses the IPC
    /// boundary, in either direction.
    #[test]
    fn taxii_credentials_are_typed_into_a_native_dialog_never_passed_in() {
        let src = include_str!("taxii.rs");
        for (name, signature) in [
            ("taxii_auth_prompt", "pub async fn taxii_auth_prompt(app: AppHandle, id: i64) -> AppResult<bool>"),
            ("taxii_auth_forget", "pub async fn taxii_auth_forget(app: AppHandle, id: i64) -> AppResult<bool>"),
        ] {
            assert!(src.contains(signature), "{name} keeps its signature: an id in, a yes or no out");
        }
        // only those two commands write or delete one
        for (fun, calls) in [("store_taxii_secret(", 1), ("delete_taxii_secret(", 1)] {
            assert_eq!(src.matches(fun).count(), calls, "{fun} in taxii.rs");
            for other in [include_str!("threat_intel.rs"), include_str!("intel.rs"), include_str!("projects.rs"), include_str!("workspace.rs")] {
                assert!(!other.contains(fun), "{fun} called elsewhere");
            }
        }
    }

    /// Mission 7: deleting a project or evidence, and clearing the activity log, the MCP audit log
    /// or the run history cannot be undone, so each is confirmed in a native dialog: a page cannot
    /// do it alone.
    #[test]
    fn destructive_commands_confirm_natively() {
        for (src, command) in [
            (include_str!("projects.rs"), "pub async fn project_delete("),
            (include_str!("workspace.rs"), "pub async fn evidence_delete("),
            (include_str!("activity.rs"), "pub async fn activity_clear("),
            (include_str!("mcp.rs"), "pub async fn mcp_audit_clear("),
            (include_str!("tools.rs"), "pub async fn exec_history_clear("),
        ] {
            let start = src.find(command).unwrap_or_else(|| panic!("{command}"));
            let body = &src[start..start + src[start..].find("\n}\n").unwrap()];
            assert!(body.contains("confirm::native("), "{command} confirms natively");
        }
    }

    /// Mission 7: the terminal command takes nothing from the page (a directory there could be a
    /// network path); its only parameter is the app handle Tauri provides.
    #[test]
    fn the_terminal_takes_no_directory_from_the_page() {
        assert!(include_str!("system.rs").contains(&["pub async fn open_terminal(", "app: AppHandle) -> AppResult<String>"].concat()));
    }

    /// Mission 8: every process start asks in a native dialog first, except tool detection's
    /// version probes (fixed catalog flags; ProjectDiscovery tools with `-duc`, so nothing is
    /// contacted). Before, a page could open terminals and start GUI tools by itself.
    #[test]
    fn programs_start_only_after_a_native_confirmation() {
        for (src, command) in [
            (include_str!("system.rs"), "pub async fn open_terminal("),
            (include_str!("tools.rs"), "pub async fn tool_launch("),
        ] {
            let start = src.find(command).unwrap_or_else(|| panic!("{command}"));
            let body = &src[start..start + src[start..].find("\n}\n").unwrap()];
            let ask = body.find("confirm::native(").unwrap_or_else(|| panic!("{command} confirms natively"));
            let spawn = body.find(".spawn()").unwrap_or_else(|| panic!("{command} starts a program"));
            assert!(ask < spawn, "{command} asks before it starts anything");
        }
        // the probes stay without a dialog, so they must stay offline: every ProjectDiscovery tool
        // probes with its update check turned off
        let catalog: serde_json::Value = serde_json::from_str(include_str!("../../catalog/tools.json")).unwrap();
        for t in catalog["tools"].as_array().unwrap() {
            let args: Vec<&str> = t["detect"]["versionArgs"].as_array().into_iter().flatten().filter_map(|a| a.as_str()).collect();
            if ["nuclei", "httpx", "katana", "naabu", "subfinder", "dnsx"].contains(&t["id"].as_str().unwrap_or_default()) {
                assert!(args.contains(&"-duc"), "{}: version probe without -duc", t["id"]);
            }
        }
    }

    #[test]
    fn unknown_secret_names_are_refused() {
        assert!(super::read_secret("not_a_known_secret").is_none());
        assert!(super::is_taxii_secret("taxii_12_0123456789abcdef"));
        for name in ["taxii_12", "taxii_", "taxii_1x", "taxii_../a", "taxii_12_0123456789ABCDEF", "taxii_12_0123456789abcde", "taxii__0123456789abcdef", "taxii_12_0123456789abcdef_"] {
            assert!(!super::is_taxii_secret(name), "{name}");
        }
    }
}
